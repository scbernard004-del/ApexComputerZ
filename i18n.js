function translate(text, lang=language){
 const source=String(text??'');if(lang==='en')return source;
 const clean=source.trim();let result=sw[clean];
 if(result===undefined){for(const p of patterns){const m=clean.match(p.regex);if(m){result=p.value.replace(/\{(\w+)\}/g,(_,k)=>m[p.names.indexOf(k)+1]);break;}}}
 if(result===undefined&&clean!==clean.toLowerCase()){const key=Object.keys(sw).find(k=>k.toUpperCase()===clean);if(key)result=sw[key].toUpperCase();}
 if(result===undefined&&clean.includes(' / '))result=clean.split(' / ').map(p=>translate(p,lang)).join(' / ');
 if(result===undefined&&clean.includes(' — '))result=clean.split(' — ').map(p=>translate(p,lang)).join(' — ');
 if(result===undefined&&clean.includes(' · '))result=clean.split(' · ').map(p=>translate(p,lang)).join(' · ');
 if(result===undefined)return source;
 return source.slice(0,source.length-source.trimStart().length)+result+source.slice(source.trimEnd().length);
}
const sources=new WeakMap();
function translatedValue(node, key, current){
 let record=sources.get(node);if(!record){record={};sources.set(node,record);}
 let entry=record[key];if(!entry||current!==entry.output)entry=record[key]={source:current,output:current};
 entry.output=translate(entry.source);return entry.output;
}
function translateDom(root=document){
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);let node;
 while(node=walker.nextNode()){
  if(!node.textContent.trim()||node.parentElement?.closest('script,style,[data-no-translate]'))continue;
  const next=translatedValue(node,'text',node.textContent);if(next!==node.textContent)node.textContent=next;
 }
 root.querySelectorAll?.('[placeholder],[aria-label],[title]').forEach(el=>{
  if(el.closest('[data-no-translate]'))return;
  for(const key of ['placeholder','aria-label','title'])if(el.hasAttribute(key)){
   const current=el.getAttribute(key),next=translatedValue(el,key,current);if(next!==current)el.setAttribute(key,next);
  }
 });
}
